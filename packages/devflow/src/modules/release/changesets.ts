import type { DevFlowModule, ModuleAction } from "../../core/types.js";
import { fileExists } from "../../core/fs-utils.js";

const changesetsModule: DevFlowModule = {
  id: "changesets",
  name: "Changesets",
  description: "Manage versioning and changelogs for monorepos & packages",
  category: "release",
  recommendedFor: ["react", "vue", "node"],

  async detect(ctx) {
    const has = fileExists(ctx.root, ".changeset/config.json");
    return { applicable: true, alreadyConfigured: has };
  },

  async plan(ctx) {
    const actions: ModuleAction[] = [];

    actions.push({
      type: "install",
      dev: true,
      packages: ["@changesets/cli", "@changesets/changelog-github"],
    });

    actions.push({
      type: "create-file",
      path: ".changeset/config.json",
      content:
        JSON.stringify(
          {
            $schema: "https://unpkg.com/@changesets/config@3.0.0/schema.json",
            changelog: [
              "@changesets/changelog-github",
              { repo: "<owner>/<repo>" },
            ],
            commit: false,
            fixed: [],
            linked: [],
            access: "restricted",
            baseBranch: "main",
            updateInternalDependencies: "patch",
            ignore: [],
          },
          null,
          2,
        ) + "\n",
      skipIfExists: true,
    });

    actions.push({
      type: "create-file",
      path: ".changeset/README.md",
      content: `# Changesets

Hello and welcome! This folder has been automatically generated by \`@changesets/cli\`.
The files held in this directory will be used to version packages and generate changelogs.

Read more at https://github.com/changesets/changesets
`,
      skipIfExists: true,
    });

    actions.push({
      type: "add-script",
      name: "changeset",
      command: "changeset",
    });
    actions.push({
      type: "add-script",
      name: "version",
      command: "changeset version",
    });
    actions.push({
      type: "add-script",
      name: "release",
      command: "changeset publish",
    });

    return actions;
  },
};

export default changesetsModule;
